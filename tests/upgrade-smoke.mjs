import assert from 'node:assert/strict';
import {MEAL_DEFINITIONS} from '../src/data/foods.js';
import {dayMealStats,mealComplete,hasFood,mealCalories,DAILY_CALORIE_TARGET} from '../src/lib/calories.js';
import {WATER_TARGET_ML,waterReached,waterPercent,formatLiters} from '../src/lib/water.js';
import {stepsReached} from '../src/lib/steps.js';
const make=(mode='carb')=>({mode,carb:'carb-1',protein1:'proteinSmall-1',veg1:'veg-1'});
assert.equal(DAILY_CALORIE_TARGET,1200);
assert.deepEqual(MEAL_DEFINITIONS.map(m=>m.calories),[200,580,200,220]);
assert.equal(mealComplete(1,make()),true);
assert.equal(mealComplete(1,{carb:'carb-1'}),false);
assert.equal(mealCalories(make()).estimated,215);
assert.equal(mealCalories({...make(),calorieOverride:'194'}).value,194);
assert.equal(mealCalories({...make(),calorieOverride:''}).value,215);
assert.equal(mealCalories({...make(),calorieOverride:'5001'}).value,215);
assert.equal(hasFood({calorieOverride:'300'}),false);
const lunch={carb:'carb-1',protein1:'proteinBig-1',protein2:'proteinBig-2',veg1:'veg-1',veg2:'veg-2',veg3:'veg-3'};
const lunchFat={mode:'fat',fat1:'fat-1',fat2:'fat-2',...lunch,carb:''};
assert.equal(mealComplete(2,lunch),true);
assert.equal(mealComplete(2,{...lunch,veg3:''}),false);
assert.equal(mealComplete(2,lunchFat),true);
assert.equal(mealComplete(2,{...lunchFat,fat2:''}),false);
assert.equal(mealCalories(lunch).value,585);
assert.equal(mealComplete(3,{mode:'bar',snackbar:'חטיף חלבון עד 210 קק״ל'}),true);
assert.equal(mealCalories({mode:'bar',snackbar:'חטיף חלבון עד 210 קק״ל'}).value,210);
assert.equal(mealComplete(3,{mode:'carb',carb:'carb-1',protein1:'proteinSmall-1'}),true);
assert.equal(mealComplete(4,{protein1:'proteinSmall-1',veg1:'veg-1',veg2:'veg-2',veg3:'veg-3'}),true);
assert.equal(mealComplete(4,{protein1:'proteinSmall-1',veg1:'veg-1'}),false);
const all={1:make(),2:lunch,3:{mode:'bar',snackbar:'חטיף חלבון עד 210 קק״ל'},4:{protein1:'proteinSmall-1',veg1:'veg-1',veg2:'veg-2',veg3:'veg-3'}};
const stats=dayMealStats(all);
assert.equal(stats.completed,4);assert.equal(stats.logged,4);assert.equal(stats.actual,1215);assert.equal(stats.allComplete,true);
assert.equal(stepsReached(10000)&&stats.allComplete,true);
assert.equal(stepsReached(9999)&&stats.allComplete,false);
assert.equal(dayMealStats({...all,4:{veg1:'veg-1'}}).completed,3);
assert.equal(WATER_TARGET_ML,3000);
assert.equal(waterReached(null),false);assert.equal(waterReached(2999),false);assert.equal(waterReached(3000),true);
assert.equal(waterPercent(1500),50);assert.equal(waterPercent(4000),100);
assert.ok(formatLiters(1500).includes('1'));
console.log('PASS: calorie math, manual overrides, complete 4 meals, green day, 3L water target.');
